CREATE TABLE IF NOT EXISTS usuario (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 nome VARCHAR(120) NOT NULL,
 data_nasc VARCHAR(10), cpf VARCHAR(14) NOT NULL UNIQUE,
 genero VARCHAR(40), telefone VARCHAR(30), endereco VARCHAR(255), email VARCHAR(180) NOT NULL UNIQUE,
 senha_hash VARCHAR(100) NOT NULL, peso DECIMAL(7,2), altura DECIMAL(4,2), sexo VARCHAR(30),
 frequencia VARCHAR(80), atividade VARCHAR(255), cardiopatia VARCHAR(10), fumo VARCHAR(30), alcool VARCHAR(50),
 saude_json LONGTEXT, restricao VARCHAR(500), objetivo VARCHAR(120), objetivo_medico VARCHAR(120), foto_url VARCHAR(500),
 criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP, atualizado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
